def build_v6_bands(gains: dict) -> list:
    """从 {频率: 增益} 字典构建 31 段 PK 滤波器列表（未列频点 gain=0）。"""
    bands = []
    for f in FREQS:
        g = gains.get(f, 0.0)
        assert -10 <= g <= 10, f"频点 {f}Hz 增益 {g}dB 超出 ±10dB 范围"
        bands.append({
            "type": TYPE_PEAK,
            "frequency": int(f),
            "q": GRID_Q,
            "gain": float(g),
        })
    return bands


